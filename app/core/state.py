"""
LangGraph shared state schema for the TrueAI incident pipeline.

All pipeline nodes read from and write to a single :class:`IncidentState`
dict.  Using ``total=False`` means every key is optional at the TypedDict
level — nodes should treat absent keys as "not yet produced" and populate
them as they execute.  This allows the graph to start with only the minimal
bootstrap fields (incident_id, user_id, raw_payload) and accumulate data
incrementally without requiring every node to initialise fields it has no
knowledge of.

Field grouping follows pipeline stage order so that the schema doubles as
human-readable documentation of the data flow.
"""

from typing import Any, Dict, List, Optional
from typing_extensions import TypedDict


class IncidentState(TypedDict, total=False):
    """
    Mutable shared state threaded through every node of the incident pipeline.

    Stage 0 — Bootstrap (required before graph entry)
    ─────────────────────────────────────────────────
    incident_id     Unique identifier for this pipeline run.  Generated by
                    the webhook handler and used as the primary key in
                    Supabase.
    user_id         Identifier of the workspace/tenant that owns this incident.
    raw_payload     The verbatim Sentry webhook payload as received by the API,
                    preserved for audit purposes and re-parsing if needed.

    Stage 1 — Parsing (parser node)
    ────────────────────────────────
    error_type      Exception class name extracted from the Sentry event
                    (e.g. "TypeError", "KeyError", "IntegrityError").
    error_message   Human-readable error string from the Sentry event.
    stack_frames    Parsed stack frames that belong to user-authored code
                    (third-party and stdlib frames are filtered out).  Each
                    entry is a dict with keys: filename, lineno, function,
                    context_line, pre_context, post_context.
    sentry_context  Additional context from the Sentry event: tags, user,
                    request, breadcrumbs, extra, release, environment, etc.

    Stage 2 — Context enrichment (context node)
    ─────────────────────────────────────────────
    github_context  File contents fetched from GitHub for every filename that
                    appears in stack_frames.  Keys are relative repo paths;
                    values are the full file content as a string.

    Stage 3 — Classification (classifier node)
    ───────────────────────────────────────────
    issue_classification
                    One of: "code_bug", "config_issue", "infrastructure",
                    "data_issue", "dependency".  Determines downstream routing
                    and the fix strategy the LLM is prompted with.

    Stage 4 — Root-cause analysis (root_cause node)
    ─────────────────────────────────────────────────
    root_cause      Concise technical description of why the error occurred,
                    as determined by the LLM.
    explanation     Longer, human-readable explanation suitable for inclusion
                    in a PR description or incident post-mortem.
    confidence      LLM self-reported confidence in the root-cause analysis,
                    normalised to [0.0, 1.0].  Used by the decision node to
                    choose between auto-fix and human escalation.

    Stage 5 — Fix generation (fix_generator node)
    ───────────────────────────────────────────────
    fix_diff        Unified diff (patch format) of the proposed code fix.
                    Applied to the repository to create the PR branch.
    files_changed   List of relative repo paths that the diff modifies.

    Stage 6 — Validation (validator node)
    ──────────────────────────────────────
    validation_passed
                    True if the generated fix passed all automated checks
                    (syntax validation, no new lint errors, diff applies
                    cleanly).  False triggers the "flag_for_review" branch.

    Stage 7 — Decision (decision node)
    ────────────────────────────────────
    action          "create_pr"        — diff is valid and confidence is high
                                         enough to open a PR automatically.
                    "flag_for_review"  — confidence is too low or validation
                                         failed; a human must review before
                                         any code is touched.

    Stage 8 — PR creation (pr_creator node)
    ─────────────────────────────────────────
    pr_url          Full HTML URL of the created GitHub pull request.
    pr_number       GitHub PR number (integer) for linking in notifications.

    Meta — populated by any node on failure
    ─────────────────────────────────────────
    error           Error message if any node raised an unhandled exception.
                    Set by the global error handler; all other fields may be
                    partially populated when this key is present.
    status          Pipeline lifecycle status.  One of:
                      "received"       — webhook accepted, pipeline not started
                      "processing"     — pipeline is running
                      "pr_created"     — completed successfully with a PR
                      "flagged"        — completed, but escalated for human review
                      "failed"         — pipeline terminated with an error
    """

    # ---- Stage 0: Bootstrap ------------------------------------------- #
    incident_id: str
    user_id: str
    raw_payload: Dict[str, Any]

    # ---- Stage 1: Parsing --------------------------------------------- #
    error_type: str
    error_message: str
    stack_frames: List[Dict[str, Any]]
    sentry_context: Dict[str, Any]

    # ---- Stage 2: Context enrichment ---------------------------------- #
    github_context: Dict[str, str]

    # ---- Stage 3: Classification -------------------------------------- #
    issue_classification: str

    # ---- Stage 4: Root-cause analysis --------------------------------- #
    root_cause: str
    explanation: str
    confidence: float

    # ---- Stage 5: Fix generation -------------------------------------- #
    fix_diff: str
    files_changed: List[str]

    # ---- Stage 6: Validation ----------------------------------------- #
    validation_passed: bool

    # ---- Stage 7: Decision ------------------------------------------- #
    action: str

    # ---- Stage 8: PR creation ---------------------------------------- #
    pr_url: str
    pr_number: int

    # ---- Meta --------------------------------------------------------- #
    error: str
    status: str


# ------------------------------------------------------------------ #
# Allowed literals — used by nodes for validation and routing         #
# ------------------------------------------------------------------ #

ISSUE_CLASSIFICATIONS = frozenset(
    {"code_bug", "config_issue", "infrastructure", "data_issue", "dependency"}
)

PIPELINE_ACTIONS = frozenset({"create_pr", "flag_for_review"})

PIPELINE_STATUSES = frozenset(
    {"received", "processing", "pr_created", "flagged", "failed"}
)


def make_initial_state(
    *,
    incident_id: str,
    user_id: str,
    raw_payload: Dict[str, Any],
) -> IncidentState:
    """
    Construct the minimal bootstrap state required to start the pipeline.

    All other fields are left absent so that TypedDict key-presence checks
    inside nodes can reliably distinguish "not yet computed" from "computed
    as empty string / zero / False".

    Args:
        incident_id:  Unique pipeline run identifier (UUID recommended).
        user_id:      Tenant / workspace identifier.
        raw_payload:  Raw Sentry webhook payload dict.

    Returns:
        An :class:`IncidentState` dict ready to pass into the compiled graph.
    """
    return IncidentState(
        incident_id=incident_id,
        user_id=user_id,
        raw_payload=raw_payload,
        status="received",
    )
