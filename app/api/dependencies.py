"""
FastAPI dependency injection for TrueAI.

Authentication model
────────────────────
Every protected route resolves to a ``user_id: str`` via one of two
credential types:

1. Bearer JWT  (Authorization: Bearer <supabase_jwt>)
   Issued by Supabase Auth on user login.  Verified locally using
   SUPABASE_JWT_SECRET — no network call required.

2. API Key  (X-API-Key: tai_xxx  OR  ?key=tai_xxx as a query param)
   Generated by POST /auth/api-keys.  Verified by hashing and looking
   up the digest in Supabase's api_keys table.

The webhook route uses the query-param variant because Sentry's webhook
configuration UI does not support custom request headers.

Dependency hierarchy
────────────────────
    get_current_user     — tries Bearer JWT then X-API-Key header
    require_current_user — identical but raises 401 if both fail
                          (use this everywhere a user is required)
    get_webhook_user     — resolves from ?key= query parameter only
                          (used exclusively by the webhook route)
"""

from __future__ import annotations

from typing import Optional

from fastapi import Depends, Header, HTTPException, Query, status
from fastapi.security import HTTPAuthorizationCredentials, HTTPBearer

from app.core.logging import get_logger

logger = get_logger(__name__)

# HTTPBearer extracts the token from "Authorization: Bearer <token>".
# auto_error=False means it returns None instead of raising 403 when
# the header is absent — we handle the fallback logic ourselves.
_bearer_scheme = HTTPBearer(auto_error=False)


# ================================================================== #
# Core resolver                                                        #
# ================================================================== #

async def get_current_user(
    credentials: Optional[HTTPAuthorizationCredentials] = Depends(_bearer_scheme),
    x_api_key: Optional[str] = Header(default=None, alias="X-API-Key"),
) -> Optional[str]:
    """
    Attempt to resolve the authenticated user from available credentials.

    Tries, in order:
    1. Bearer JWT in the Authorization header.
    2. API key in the X-API-Key header.

    Returns:
        The resolved ``user_id`` string, or ``None`` if no credential was
        presented (not if a credential was wrong — wrong credentials raise
        401 immediately).

    Raises:
        HTTPException(401) for malformed or invalid credentials.
    """
    # ---- Attempt 1: Bearer JWT --------------------------------------- #
    if credentials is not None:
        token = credentials.credentials
        try:
            from app.auth.jwt import get_user_id_from_token
            user_id = get_user_id_from_token(token)
            logger.debug("Auth: JWT resolved user_id=%s.", _mask(user_id))
            return user_id
        except HTTPException:
            # Re-raise 401s from the JWT verifier as-is
            raise
        except Exception as exc:
            logger.warning("Auth: unexpected JWT error: %s", exc)
            raise HTTPException(
                status_code=status.HTTP_401_UNAUTHORIZED,
                detail="Invalid or expired token.",
                headers={"WWW-Authenticate": "Bearer"},
            )

    # ---- Attempt 2: X-API-Key header -------------------------------- #
    if x_api_key:
        user_id = _resolve_api_key(x_api_key)
        if user_id:
            logger.debug(
                "Auth: API key resolved user_id=%s.", _mask(user_id)
            )
            return user_id
        # Key was presented but is invalid — fail hard
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or revoked API key.",
        )

    # No credentials presented
    return None


async def require_current_user(
    user_id: Optional[str] = Depends(get_current_user),
) -> str:
    """
    Dependency that enforces authentication.

    Use this on every route that requires a logged-in user.  Returns the
    ``user_id`` string unconditionally (raises 401 if absent).

    Raises:
        HTTPException(401) when no valid credential is present.
    """
    if not user_id:
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Authentication required.",
            headers={"WWW-Authenticate": "Bearer"},
        )
    return user_id


# ================================================================== #
# Webhook-specific resolver (query param)                              #
# ================================================================== #

async def get_webhook_user(
    key: str = Query(
        ...,
        description=(
            "API key for webhook authentication.  "
            "Passed as a query parameter because Sentry does not support "
            "custom request headers in webhook configurations."
        ),
        min_length=1,
    ),
) -> str:
    """
    Resolve a ``user_id`` from the ``?key=`` query parameter.

    Used exclusively by the Sentry webhook endpoint.

    Raises:
        HTTPException(401) for missing, invalid, or revoked keys.
    """
    user_id = _resolve_api_key(key)
    if not user_id:
        logger.warning(
            "Webhook auth: invalid API key presented (prefix=%s...).",
            key[:6] if len(key) >= 6 else "****",
        )
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Invalid or revoked webhook API key.",
        )
    return user_id


# ================================================================== #
# Internal helpers                                                     #
# ================================================================== #

def _resolve_api_key(raw_key: str) -> Optional[str]:
    """
    Hash *raw_key* and look it up in Supabase.  Returns user_id or None.

    Supabase errors are caught and logged — the caller decides whether a
    None result means "key not found" or "DB unavailable".  In either case
    the result from the caller's perspective is the same: deny access.
    """
    try:
        from app.services.supabase import get_user_by_api_key
        return get_user_by_api_key(raw_key)
    except Exception as exc:
        logger.error("_resolve_api_key: Supabase lookup failed: %s", exc)
        return None


def _mask(user_id: str) -> str:
    """Return first 8 chars of user_id for safe log output."""
    return f"{user_id[:8]}..." if len(user_id) > 8 else "****"
